/**
 * Offline-shell registration for the base product.
 *
 * Scope and URL both come from Vite's `BASE_URL`, so the worker is pinned to
 * `/reader/` in the release build and cannot accidentally claim the whole
 * origin. Registering the *same* `<base>sw.js` with `<base>` as its scope is
 * also what keeps a second deployment at a different path from fighting over
 * one registration.
 *
 * The worker itself is generated by `apps/reader-release/build.mjs`; it caches
 * only same-origin GET responses. This function is deliberately forgiving —
 * a browser without service-worker support, an insecure origin (plain
 * `http://` on a non-loopback host) or a registration failure all degrade to
 * "no offline cache" while the app keeps working online.
 */

export function registerOfflineShell(): void {
  if (typeof navigator === "undefined" || !("serviceWorker" in navigator)) return;
  if (typeof window === "undefined" || !window.isSecureContext) return;

  const base = import.meta.env.BASE_URL || "/";

  window.addEventListener("load", () => {
    void navigator.serviceWorker
      .register(`${base}sw.js`, { scope: base })
      .catch(() => {
        /* No offline shell; the app still works online. */
      });
  });
}

/**
 * Base-line build config.
 *
 * This is a *release configuration*, not a second application. It builds the
 * repo's existing `index.html` and `src/**` — the base product — with four
 * differences, and nothing else:
 *
 *   1. `base: "/reader/"`, so the bundle deploys under a path instead of a
 *      domain root. Every emitted asset URL and the injected service-worker
 *      registration are relative to that base.
 *   2. An HTML transform that (a) drops the three Google Fonts `<link>`s so a
 *      default page load makes **no** remote request, (b) replaces the default
 *      CSP with one that keeps `script-src 'self'` but allows
 *      `connect-src https:`, because a BYOK key is sent to whatever
 *      OpenAI-compatible endpoint the user configures, and (c) writes the
 *      document head a crawler needs — title, description, Open
 *      Graph, Twitter card, indexing directive and a `WebApplication` block.
 *   3. A pre-rendered shell inside `#root`, so the page has real content before
 *      (and without) JavaScript. The deployed URL used to answer with
 *      `<div id="root"></div>` and nothing else; a crawler that does not run
 *      scripts saw an empty document, and a reader on a slow connection saw a
 *      blank frame. React clears the container on the first render, so the
 *      shell is what a no-JS fetch reads and what a JS fetch replaces.
 *   4. Chunk splitting for the three heavyweight, non-critical graphs — the PDF
 *      engine, the Markdown pipeline, and the model client — so a reader who
 *      never opens a PDF does not re-download the PDF engine when an unrelated
 *      chunk changes, and so first paint does not wait on one 800 KB entry.
 *
 * The head is written here rather than in a host-site template because this
 * build *is* the document: a deployment publishes this `dist/` and nothing
 * else under `/reader/`.
 *
 * `frame-ancestors` is the one directive that is dropped from the meta copy
 * (`META_CSP`) and kept in the header copy (`FREE_CSP`): a meta-delivered
 * `frame-ancestors` is ignored by browsers, so shipping it there only produced
 * a console warning on every load.
 *
 * It does not set a release channel. The account and cloud surface is composed
 * at runtime through the optional contract in `src/lib/cloud/`, so the shell
 * does not branch on a channel literal. The
 * service worker is registered from `src/main.tsx` and generated by
 * `build.mjs`; nothing here injects it, because a tag injected after Vite's
 * own HTML pass would make the output differ in a way nothing could assert
 * against.
 *
 * Run from the repository root:
 *   npx vite build --config apps/reader-release/vite.config.ts
 */

import { defineConfig, type Plugin } from "vite";
import react from "@vitejs/plugin-react";
import path from "path";
import { FREE_CSP, META_CSP, DEPLOY_BASE } from "./csp.js";

const ROOT = path.resolve(__dirname, "../..");
const OUT_DIR = path.resolve(__dirname, "dist");

/**
 * The page's name — in the tab and in a share card alike.
 *
 * It used to be a marketing sentence ("KoBook 中文阅读器 · 选中文字，读懂疑问").
 * Three clauses in a tab is noise, and an `og:title` that disagrees with
 * `<title>` tells two readers of the same page two different things — which is
 * exactly what `REQUIRED_HEAD` in `build.mjs` exists to prevent. The
 * descriptive half did not disappear: it is the description, the `<h1>` and the
 * no-JS shell below.
 */
const TITLE = "KoBook";
/**
 * Written for a search result, not for the app: one sentence of what it is,
 * one of what it does, one of where the data lives. The last clause is the
 * part a reader actually needs before they paste a document into a stranger's
 * website, and it is true — articles and notes stay in this browser.
 */
const DESCRIPTION =
  "KoBook 中文阅读器：粘贴链接或导入 PDF、EPUB、DOCX，选中不懂的词句就地解释。文章和笔记默认保存在你的浏览器里，只有你主动提问时才联网。";

const SHELL = `
    <div class="seo-shell">
      <header>
        <p class="seo-shell__brand">KoBook</p>
        <h1>选中文字，读懂疑问</h1>
        <p class="seo-shell__lede">${DESCRIPTION}</p>
      </header>
      <section>
        <h2>它能做什么</h2>
        <ul>
          <li>网页正文提取：粘贴链接，取回干净正文再读，广告和导航留在原文里。</li>
          <li>本地导入：PDF、EPUB、DOCX、HTML、Markdown、TXT 直接进书架，文件不上传。</li>
          <li>选中即问：划词解释、翻译、追问，答案贴着原文，不另开一页。</li>
          <li>笔记与导出：段落旁批注，按文章导出一份 Markdown 笔记本。</li>
          <li>离线可用：装过一次之后，断网也能打开读过的内容。</li>
        </ul>
      </section>
      <section>
        <h2>你的内容在哪里</h2>
        <p>文章、笔记和阅读偏好存在这台设备的浏览器存储里。账号与云同步是可选的；模型调用走你自己的 API Key，或走本站的匿名提取通道——一次划词不会把整篇文章传出去。</p>
      </section>
      <p class="seo-shell__hint"><a href="${DEPLOY_BASE}">打开阅读器</a>（界面需要启用 JavaScript；以上内容无需脚本即可阅读）</p>
    </div>
`;

/**
 * CSP for the base line — see `./csp.ts` for the rationale. It lives in its
 * own module because the service sets the same policy as a header.
 */
function baseLineHtml(): Plugin {
  return {
    name: "reader-release:base-line-html",
    transformIndexHtml: {
      order: "pre",
      handler(html) {
        let out = html;
        // 1. No remote fonts by default. The CSS font stacks already fall
        //    back to locally available families, so nothing breaks offline.
        out = out.replace(/<link[^>]*fonts\.googleapis\.com[^>]*>/g, "");
        out = out.replace(/<link[^>]*fonts\.gstatic\.com[^>]*>/g, "");

        // 2. Base-line CSP. `META_CSP` drops the header-only directive.
        out = out.replace(
          /<meta\s+http-equiv="Content-Security-Policy"[\s\S]*?\/>/,
          `<meta\n      http-equiv="Content-Security-Policy"\n      content="${META_CSP}"\n    />`,
        );

        // 3. Document head a crawler can use: a description, a share title and
        //    the install icons. No canonical URL and no absolute share image —
        //    this build has no fixed origin; it is served wherever it is served.
        out = out.replace(
          "</head>",
          `    <meta name="description" content="${DESCRIPTION}" />
    <meta name="robots" content="index,follow,max-image-preview:large" />
    <link rel="icon" type="image/svg+xml" href="${DEPLOY_BASE}favicon.svg" />
    <link rel="apple-touch-icon" sizes="180x180" href="${DEPLOY_BASE}apple-touch-icon.png" />
    <link rel="manifest" href="${DEPLOY_BASE}manifest.json" />
    <meta name="theme-color" content="#000000" />
    <meta property="og:type" content="website" />
    <meta property="og:site_name" content="KoBook" />
    <meta property="og:locale" content="zh_CN" />
    <meta property="og:title" content="${TITLE}" />
    <meta property="og:description" content="${DESCRIPTION}" />
    <meta name="twitter:card" content="summary_large_image" />
    <meta name="twitter:title" content="${TITLE}" />
    <meta name="twitter:description" content="${DESCRIPTION}" />
  </head>`,
        );

        // 4. The shell. Only replaced when `index.html` still has the empty
        //    mount point; a mismatch fails the release assertion in
        //    `build.mjs` rather than shipping a page that renders twice.
        out = out.replace(
          /<div id="root"><\/div>/,
          `<div id="root">${SHELL}    </div>`,
        );
        return out;
      },
    },
  };
}

export default defineConfig({
  root: ROOT,
  base: DEPLOY_BASE,
  plugins: [react(), baseLineHtml()],
  resolve: {
    alias: {
      "@": path.resolve(ROOT, "./src"),
    },
  },
  build: {
    outDir: OUT_DIR,
    emptyOutDir: true,
    sourcemap: false,
    rollupOptions: {
      output: {
        /**
         * Split by *what a page needs*, not by vendor. These three graphs are
         * the ones that are large, self-contained and not needed to paint the
         * shell: the PDF engine (`pdfjs-dist`, an order of magnitude larger
         * than anything else here), the Markdown pipeline (unified + remark,
         * pulled in by import and paste), and the model client (the AI SDK).
         * Everything else stays in the entry, where Rollup can still tree-shake
         * it against the app's own code.
         */
        manualChunks(id: string) {
          if (!id.includes("node_modules")) return undefined;
          if (/[\\/]node_modules[\\/]pdfjs-dist[\\/]/.test(id)) return "vendor-pdf";
          if (/[\\/]node_modules[\\/](@ai-sdk|ai)[\\/]/.test(id)) return "vendor-ai";
          if (
            /[\\/]node_modules[\\/](unified|remark-[a-z-]+|mdast-[a-z-]+|micromark[a-z-]*|vfile[a-z-]*|unist-[a-z-]+)[\\/]/.test(
              id,
            )
          ) {
            return "vendor-markdown";
          }
          return undefined;
        },
      },
    },
  },
});

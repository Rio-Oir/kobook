/**
 * Shippable-build configuration.
 *
 * This is a *release configuration*, not a second application. It builds the
 * repo's existing `index.html` and `src/**` — the base product — with three
 * differences, and nothing else:
 *
 *   1. `base: "/reader/"`, so the bundle deploys under a path instead of a
 *      domain root. Every emitted asset URL and the injected service-worker
 *      registration are relative to that base.
 *   2. An HTML transform that (a) drops the three Google Fonts `<link>`s so a
 *      default page load makes **no** remote request, and (b) replaces the
 *      default CSP with one that keeps `script-src 'self'` but allows
 *      `connect-src https:`, because a BYOK key is sent to whatever
 *      OpenAI-compatible endpoint the user configures.
 *   3. A resolved-path alias for `@/`, matching the root config.
 *
 * It never sets a release channel. There is no channel: the account and
 * cloud code is not in this tree, so "this build has no accounts" is a
 * property of the module graph rather than of a build-time literal. The
 * service worker is registered from `src/main.tsx` and generated by
 * `build.mjs`; nothing here injects it, because a tag injected after Vite's
 * own HTML pass would make the output differ in a way nothing could assert
 * against.
 *
 * Run from the repository root:
 *   npx vite build --config apps/reader-release/vite.config.ts
 */

import { defineConfig, type Plugin } from "vite";
import react from "@vitejs/plugin-react";
import path from "path";
import { BASE_CSP, DEPLOY_BASE } from "./csp.js";

const ROOT = path.resolve(__dirname, "../..");
const OUT_DIR = path.resolve(__dirname, "dist");

/**
 * CSP for this build — see `./csp.ts` for the rationale. It lives in its own
 * module because the service sets the same policy as a header.
 */
function baseLineHtml(): Plugin {
  return {
    name: "reader-release:base-line-html",
    transformIndexHtml: {
      order: "pre",
      handler(html) {
        let out = html;
        // 1. No remote fonts by default. The CSS font stacks already fall
        //    back to locally available families, so nothing breaks offline.
        out = out.replace(/<link[^>]*fonts\.googleapis\.com[^>]*>/g, "");
        out = out.replace(/<link[^>]*fonts\.gstatic\.com[^>]*>/g, "");

        // 2. Base-line CSP.
        out = out.replace(
          /<meta\s+http-equiv="Content-Security-Policy"[\s\S]*?\/>/,
          `<meta\n      http-equiv="Content-Security-Policy"\n      content="${BASE_CSP}"\n    />`,
        );
        return out;
      },
    },
  };
}

export default defineConfig({
  root: ROOT,
  base: DEPLOY_BASE,
  plugins: [react(), baseLineHtml()],
  resolve: {
    alias: {
      "@": path.resolve(ROOT, "./src"),
    },
  },
  build: {
    outDir: OUT_DIR,
    emptyOutDir: true,
    sourcemap: false,
  },
});

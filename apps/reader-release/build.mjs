/**
 * Base-line release build.
 *
 * Two steps, both idempotent:
 *   1. `vite build` with `apps/reader-release/vite.config.ts` (existing
 *      `index.html` + `src/**`, `base: "/reader/"`).
 *   2. Emit the offline shell into `dist/`: a content-versioned service
 *      worker plus its registration shim.
 *
 * Why the worker is generated here rather than living in the app's `src/`:
 * it has to enumerate every emitted file by name, which is only knowable after
 * the bundle is written. The worker caches **only** same-origin GET responses.
 * Cross-origin traffic (the Jina reader, the user's BYOK model endpoint) is
 * passed straight to the network — a cached model response would be both wrong
 * and a privacy surprise — and the cache never holds anything from `/api/`.
 *
 * The build asserts two things about its own output rather than trusting the
 * config: that the account/cloud surface is *absent*, and that the
 * anonymous-extraction surface is *present*. Both are checked against the
 * emitted bytes, so a dependency that sneaks back in through a transitive
 * import fails the build instead of shipping.
 *
 * Usage (from the repository root):
 *   node apps/reader-release/build.mjs
 */

import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readdir, readFile, writeFile, stat, rm } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(HERE, "../..");
const DIST = path.join(HERE, "dist");
const BASE = "/reader/";

async function walk(dir, prefix = "") {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const rel = prefix + entry.name;
    if (entry.isDirectory()) out.push(...(await walk(path.join(dir, entry.name), `${rel}/`)));
    else out.push(rel);
  }
  return out;
}

function run(command, args) {
  const result = spawnSync(command, args, {
    cwd: REPO_ROOT,
    stdio: "inherit",
    shell: process.platform === "win32",
  });
  if (result.status !== 0) {
    console.error(`\n[reader-release] FAILED: ${command} ${args.join(" ")} (exit ${result.status})`);
    process.exit(result.status ?? 1);
  }
}

function buildWorker(files, version) {
  return `// Generated by apps/reader-release/build.mjs -- do not edit by hand.
// Offline shell for this build, scoped to ${BASE}.
const NAME = 'kobook-shell-${version}';
const FILES = ${JSON.stringify(["./", ...files.map((f) => `./${f}`)])};

self.addEventListener('install', (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(NAME);
      await cache.addAll(FILES);
      await self.skipWaiting();
    })(),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(self.clients.claim());
});

// Keep previously installed shells: a tab left open across a deploy still
// requests its old hashed assets. User data is never stored here.
self.addEventListener('fetch', (event) => {
  const request = event.request;
  let url;
  try {
    url = new URL(request.url);
  } catch {
    return;
  }
  // Cross-origin (Jina reader, the user's model endpoint): never intercept.
  // Falling through leaves the request exactly as the page issued it.
  if (url.origin !== self.location.origin) return;
  if (!url.pathname.startsWith('/reader/')) return;
  if (request.method !== 'GET') return;
  // The base build has no account/cloud API surface, but refuse to cache one anyway.
  if (url.pathname.startsWith('/api/')) return;

  event.respondWith(
    (async () => {
      const cache = await caches.open(NAME);
      const hit = await cache.match(request, { ignoreSearch: true });
      if (hit) return hit;
      if (url.pathname.includes('/assets/')) {
        const previous = await caches.match(request);
        if (previous) return previous;
      }
      if (request.mode === 'navigate') {
        const shell = await cache.match('./index.html');
        if (shell) return shell;
      }
      try {
        return await fetch(request);
      } catch (err) {
        // Offline and not cached: fail the request rather than inventing a
        // response, so the page's own error handling is what the user sees.
        throw err;
      }
    })(),
  );
});
`;
}

const REGISTER_NOTE = `Registration lives in src/sw-register.ts (called from src/main.tsx)
so it is bundled and typechecked with the rest of the app; only the worker
itself is generated here.`;

async function emitShell() {
  const files = (await walk(DIST)).filter((f) => f !== "sw.js").sort();
  const hash = createHash("sha256");
  for (const file of files) {
    hash.update(file);
    hash.update(await readFile(path.join(DIST, file)));
  }
  const version = hash.digest("hex").slice(0, 20);

  await writeFile(path.join(DIST, "sw.js"), buildWorker(files, version), "utf8");
  await writeFile(
    path.join(HERE, "build-manifest.json"),
    JSON.stringify({ name: "kobook", base: BASE, version, files }, null, 2),
    "utf8",
  );
  console.log(`[reader-release] offline shell ${version} over ${files.length} files`);
}

async function main() {
  // Clean explicitly before building. The offline shell lists every emitted
  // file by name, so a stale asset left behind by a previous build would be
  // cached forever by any browser that installed that shell — and a hashed
  // filename that no longer belongs to the build is not something a later
  // diff would notice.
  await rm(DIST, { recursive: true, force: true });
  run("npx", ["vite", "build", "--config", "apps/reader-release/vite.config.ts"]);

  const indexHtml = await readFile(path.join(DIST, "index.html"), "utf8");
  // Only the reviewed theme bootstrap may run inline; never reopen arbitrary
  // inline execution to accommodate a changed bootstrap.
  const inlineScripts = [...indexHtml.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g)];
  if (inlineScripts.length !== 1 || !indexHtml.includes(
    `sha256-${createHash("sha256").update(inlineScripts[0][1].replace(/\r\n/g, "\n")).digest("base64")}`,
  ) || /script-src[^;]*'unsafe-inline'/.test(indexHtml)) {
    throw new Error("the CSP must hash only the reviewed theme bootstrap");
  }
  // ── Artifact assertions ─────────────────────────────────────────────────
  //
  // These read the emitted bytes, not the config. The previous check asserted
  // that a build-time literal had reached the bundle; that flag is gone, and
  // asserting on the *absence* of an account/cloud surface is both a stronger
  // claim and one no flag can satisfy by accident.
  const jsFiles = (await walk(path.join(DIST, "assets"))).filter((f) => f.endsWith(".js"));
  let bundle = "";
  for (const file of jsFiles) {
    bundle += await readFile(path.join(DIST, "assets", file), "utf8");
  }

  // 1. The bundle names no same-origin API path the contract does not declare.
  //
  // Absolute URLs are removed first, because a `/api/...` path inside one
  // belongs to somebody else's server — the BYOK provider presets contain
  // `https://openrouter.ai/api/v1`, which is not this service's route. What is
  // left is a path this application would request from its own origin.
  //
  // The declared set is read out of `shared/contracts/api.ts` rather than
  // listed here, so the assertion cannot drift from the route table: adding a
  // path to the contract widens it automatically, and a *client* for some
  // other route — an account probe, a sync call, an admin or sample endpoint —
  // is exactly what this catches.
  const contractSource = await readFile(path.join(REPO_ROOT, "shared/contracts/api.ts"), "utf8");
  const declaredApiPaths = new Set(
    [...contractSource.matchAll(/"[^"]*\/api\/[^"]*"/g)].map((m) => m[0].slice(1, -1)),
  );
  const sameOriginText = bundle.replace(/https?:\/\/[^\s"'`()\\]+/g, " ");
  const apiPathsInBundle = new Set(sameOriginText.match(/\/api\/[A-Za-z0-9/_-]*/g) ?? []);
  const undeclared = [...apiPathsInBundle].filter((path) => !declaredApiPaths.has(path));
  if (undeclared.length > 0) {
    console.error(
      `[reader-release] FAILED: bundle references API paths outside the contract: ${undeclared.join(", ")}`,
    );
    process.exit(1);
  }
  // The database driver and auth vendor the parent product used are not in
  // `package.json`, so they cannot be in the module graph or the lockfile.
  // That is the dependency-level guarantee; these byte-level checks are the
  // independent one, and neither substitutes for the other.

  // 2. The base surface is actually present. A positive control, so "no
  //    account code" cannot be satisfied by an empty or truncated bundle.
  for (const required of ["/api/anonymous/extract", "sw.js"]) {
    if (!bundle.includes(required)) {
      console.error(`[reader-release] FAILED: base bundle is missing ${required}`);
      process.exit(1);
    }
  }
  if (indexHtml.includes("fonts.googleapis.com") || indexHtml.includes("fonts.gstatic.com")) {
    console.error("[reader-release] FAILED: built index.html still links remote fonts");
    process.exit(1);
  }
  if (!indexHtml.includes("connect-src 'self' https:")) {
    console.error("[reader-release] FAILED: built index.html did not get the base-line CSP");
    process.exit(1);
  }
  const assetStats = await stat(path.join(DIST, "index.html"));
  if (!assetStats.isFile()) {
    console.error("[reader-release] FAILED: dist/index.html missing");
    process.exit(1);
  }

  await emitShell();
  console.log(`[reader-release] built ${DIST} (base ${BASE})`);
}

await main();

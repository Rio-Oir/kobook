/**
 * Base-line release build.
 *
 * Two steps, both idempotent:
 *   1. `vite build` with `apps/reader-release/vite.config.ts` (existing
 *      `index.html` + `src/**`, `base: "/reader/"`).
 *   2. Emit the offline shell into `dist/`: a content-versioned service
 *      worker plus its registration shim.
 *
 * Why the worker is generated here rather than living in the app's `src/`:
 * it has to enumerate every emitted file by name, which is only knowable after
 * the bundle is written. The worker caches **only** same-origin GET responses.
 * Cross-origin traffic (the Jina reader, the user's BYOK model endpoint) is
 * passed straight to the network — a cached model response would be both wrong
 * and a privacy surprise — and the cache never holds anything from `/api/`.
 *
 * The build asserts three things about its own output rather than trusting the
 * config: that the **payment, entitlement and platform-AI** surface is
 * *absent*, that the reader's own surface — anonymous extraction *and* the
 * account, article and note routes — is *present*, and that no source file
 * reaches for a `modules/**` package. The first two are checked against the
 * emitted bytes, so a dependency that sneaks back in through a transitive
 * import fails the build instead of shipping; the third is checked against the
 * sources, because a module that is never imported into the bundle is exactly
 * the kind of thing a byte-level check cannot see.
 *
 * The line this draws is **payment, not accounts**. Accounts, sessions, cloud
 * sync and cloud notes are part of the open-source product; what is not is the
 * ability to take money. A deployment of this build with no payment
 * configuration anywhere is a complete product, not a crippled one.
 *
 * Usage (from the repository root):
 *   node apps/reader-release/build.mjs
 */

import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readdir, readFile, writeFile, stat, rm } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(HERE, "../..");
const DIST = path.join(HERE, "dist");
const BASE = "/reader/";

async function walk(dir, prefix = "") {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const rel = prefix + entry.name;
    if (entry.isDirectory()) out.push(...(await walk(path.join(dir, entry.name), `${rel}/`)));
    else out.push(rel);
  }
  return out;
}

function run(command, args) {
  const result = spawnSync(command, args, {
    cwd: REPO_ROOT,
    stdio: "inherit",
    shell: process.platform === "win32",
  });
  if (result.status !== 0) {
    console.error(`\n[reader-release] FAILED: ${command} ${args.join(" ")} (exit ${result.status})`);
    process.exit(result.status ?? 1);
  }
}

function buildWorker(files, version) {
  return `// Generated by apps/reader-release/build.mjs -- do not edit by hand.
// Offline shell for the base build, scoped to ${BASE}.
const NAME = 'gloss-free-shell-${version}';
const FILES = ${JSON.stringify(["./", ...files.map((f) => `./${f}`)])};

self.addEventListener('install', (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(NAME);
      await cache.addAll(FILES);
      await self.skipWaiting();
    })(),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(self.clients.claim());
});

// Keep previously installed shells: a tab left open across a deploy still
// requests its old hashed assets. User data is never stored here.
self.addEventListener('fetch', (event) => {
  const request = event.request;
  let url;
  try {
    url = new URL(request.url);
  } catch {
    return;
  }
  // Cross-origin (Jina reader, the user's model endpoint): never intercept.
  // Falling through leaves the request exactly as the page issued it.
  if (url.origin !== self.location.origin) return;
  if (!url.pathname.startsWith('/reader/')) return;
  if (request.method !== 'GET') return;
  // The reader's API surface is real — accounts, articles, notes — and none of
  // it belongs in the shell cache. A cached API response would be one account's
  // data handed to whoever asks next.
  if (url.pathname.startsWith('/api/')) return;

  event.respondWith(
    (async () => {
      const cache = await caches.open(NAME);
      const hit = await cache.match(request, { ignoreSearch: true });
      if (hit) return hit;
      if (url.pathname.includes('/assets/')) {
        const previous = await caches.match(request);
        if (previous) return previous;
      }
      if (request.mode === 'navigate') {
        const shell = await cache.match('./index.html');
        if (shell) return shell;
      }
      try {
        return await fetch(request);
      } catch (err) {
        // Offline and not cached: fail the request rather than inventing a
        // response, so the page's own error handling is what the user sees.
        throw err;
      }
    })(),
  );
});
`;
}

const REGISTER_NOTE = `Registration lives in src/sw-register.ts (called from src/main.tsx)
so it is bundled and typechecked with the rest of the app; only the worker
itself is generated here.`;

async function emitShell() {
  const files = (await walk(DIST)).filter((f) => f !== "sw.js").sort();
  const hash = createHash("sha256");
  for (const file of files) {
    hash.update(file);
    hash.update(await readFile(path.join(DIST, file)));
  }
  const version = hash.digest("hex").slice(0, 20);

  await writeFile(path.join(DIST, "sw.js"), buildWorker(files, version), "utf8");
  await writeFile(
    path.join(HERE, "build-manifest.json"),
    JSON.stringify({ channel: "free", base: BASE, version, files }, null, 2),
    "utf8",
  );
  console.log(`[reader-release] offline shell ${version} over ${files.length} files`);
}

async function main() {
  // Clean explicitly before building. The offline shell lists every emitted
  // file by name, so a stale asset left behind by a previous build would be
  // cached forever by any browser that installed that shell — and a hashed
  // filename that no longer belongs to the build is not something a later
  // diff would notice.
  await rm(DIST, { recursive: true, force: true });
  run("npx", ["vite", "build", "--config", "apps/reader-release/vite.config.ts"]);

  const indexHtml = await readFile(path.join(DIST, "index.html"), "utf8");
  // Only the reviewed theme bootstrap may run inline; never reopen arbitrary
  // inline execution to accommodate a changed bootstrap.
  //
  // A `type="application/ld+json"` block is a data island: the browser parses
  // it and never executes it. This build emits none, but the exclusion stays
  // because a data island added later must not be mistaken for executable
  // inline script and force a hash onto JSON.
  const inlineScripts = [
    ...indexHtml.matchAll(
      /<script(?![^>]*\bsrc=)(?![^>]*type="application\/ld\+json")[^>]*>([\s\S]*?)<\/script>/g,
    ),
  ];
  if (inlineScripts.length !== 1 || !indexHtml.includes(
    `sha256-${createHash("sha256").update(inlineScripts[0][1].replace(/\r\n/g, "\n")).digest("base64")}`,
  ) || /script-src[^;]*'unsafe-inline'/.test(indexHtml)) {
    throw new Error("Free CSP must hash only the reviewed theme bootstrap");
  }
  // ── Document head and shell ─────────────────────────────────────────────
  //
  // The head is the part of this build a crawler reads and the part nothing
  // else in the repository would notice going missing: an unescaped
  // description breaks nothing a browser does. Each string below is written by
  // `apps/reader-release/vite.config.ts`, so a rename that forgets one of them
  // fails here rather than shipping a page that says two different things to
  // two different readers.
  const REQUIRED_HEAD = [
    '<meta name="description" content="KoBook ',
    '<meta name="robots" content="index,follow,max-image-preview:large" />',
    '<meta property="og:title" content="KoBook" />',
    '<link rel="icon" type="image/svg+xml" href="/reader/favicon.svg" />',
    '<link rel="apple-touch-icon" sizes="180x180" href="/reader/apple-touch-icon.png" />',
    '<link rel="manifest" href="/reader/manifest.json" />',
  ];
  const missingHead = REQUIRED_HEAD.filter((needle) => !indexHtml.includes(needle));
  if (missingHead.length > 0) {
    console.error(`[reader-release] FAILED: dist/index.html is missing ${missingHead.join(", ")}`);
    process.exit(1);
  }
  // The installed-app icon set, same reasoning as the share image one notch
  // stronger: a `<link rel="manifest">` that resolves to a missing file is an
  // *explicit* broken promise — the CSP already allows `manifest-src 'self'`
  // and a service worker is registered at the same base, so the page is a real
  // PWA that was advertising an install icon it did not ship. Each entry is
  // listed here because `public/manifest.json` names them: the manifest is the
  // only place that knows the whole set, and it is a data file nothing
  // validates. `maskable` is separate because Android crops it differently and
  // a build that drops it still looks fine in a browser.
  const manifestRaw = await readFile(path.join(DIST, "manifest.json"), "utf8").catch(() => null);
  if (manifestRaw === null) {
    console.error("[reader-release] FAILED: dist/manifest.json is missing — the head links to it");
    process.exit(1);
  }
  let manifest;
  try {
    manifest = JSON.parse(manifestRaw);
  } catch {
    console.error("[reader-release] FAILED: dist/manifest.json is not valid JSON");
    process.exit(1);
  }
  if (manifest.start_url !== "/reader/" || manifest.scope !== "/reader/") {
    console.error(
      `[reader-release] FAILED: manifest start_url/scope must both be /reader/ — got ` +
        `${JSON.stringify(manifest.start_url)} / ${JSON.stringify(manifest.scope)}`,
    );
    process.exit(1);
  }
  const declaredIcons = Array.isArray(manifest.icons) ? manifest.icons : [];
  if (!declaredIcons.some((i) => i.purpose === "maskable")) {
    console.error("[reader-release] FAILED: manifest declares no maskable icon — Android would crop the 'any' one");
    process.exit(1);
  }
  for (const icon of declaredIcons) {
    if (typeof icon.src !== "string" || !icon.src.startsWith(BASE)) {
      console.error(`[reader-release] FAILED: manifest icon src must be absolute under ${BASE} — got ${icon.src}`);
      process.exit(1);
    }
    const onDisk = await stat(path.join(DIST, icon.src.slice(BASE.length))).catch(() => null);
    if (!onDisk || !onDisk.isFile()) {
      console.error(`[reader-release] FAILED: manifest icon ${icon.src} does not exist in dist/`);
      process.exit(1);
    }
  }
  // `frame-ancestors` is header-only: a meta copy is ignored, and shipping it
  // there put a console warning on every load. It stays in the header copy.
  const metaCsp = indexHtml.match(
    /http-equiv="Content-Security-Policy"\s+content="([^"]*)"/,
  )?.[1];
  if (!metaCsp || !metaCsp.includes("default-src 'self'") || metaCsp.includes("frame-ancestors")) {
    console.error("[reader-release] FAILED: meta CSP is missing or still carries frame-ancestors");
    process.exit(1);
  }
  // The pre-rendered shell: a fetch that runs no scripts must get prose, not an
  // empty mount point. `#root` has to stay, because React mounts into it and
  // clears it on the first render.
  if (!/<div id="root">\s*<div class="seo-shell">/.test(indexHtml)) {
    console.error("[reader-release] FAILED: dist/index.html has no pre-rendered shell");
    process.exit(1);
  }

  // ── Artifact assertions ─────────────────────────────────────────────────
  //
  // These read the emitted bytes, not the config. The check that used to live
  // here asserted the *absence* of the account and cloud surface; that claim
  // is no longer true and no longer wanted — accounts are part of this product.
  // What replaces it is the same kind of claim about the surface that must
  // never ship: the payment, entitlement and platform-AI one.
  const jsFiles = (await walk(path.join(DIST, "assets"))).filter((f) => f.endsWith(".js"));
  let bundle = "";
  for (const file of jsFiles) {
    bundle += await readFile(path.join(DIST, "assets", file), "utf8");
  }

  // 1. No payment, entitlement or platform-AI surface, and no path to one.
  //
  // The markers are the names those modules bring with them. `outTradeNo` is
  // the payment module's own order identifier, `EntitlementRecord` is the
  // entitlement table, and the channel prefixes are the merchant
  // configuration's environment names — none of them has any other reason to
  // appear in a reader. `套餐` is here because it is the user-visible entry the
  // billing page renders: a route table can be stripped and a link can be left
  // behind, which is precisely the failure this catches.
  const FORBIDDEN = [
    "payment-kit",
    "commercial-entitlements",
    "/api/billing",
    "BILLING_UNAVAILABLE",
    "outTradeNo",
    "EntitlementRecord",
    "WECHAT_PAY_",
    "ALIPAY_",
    "套餐",
  ];
  const leaked = FORBIDDEN.filter((marker) => bundle.includes(marker));
  if (leaked.length > 0) {
    console.error(
      `[reader-release] FAILED: base bundle contains payment/entitlement surface: ${leaked.join(", ")}`,
    );
    process.exit(1);
  }

  // 2. The reader's own surface is actually present. A positive control, so
  //    "no payment code" cannot be satisfied by an empty or truncated bundle —
  //    and the account routes are listed here rather than merely tolerated,
  //    because a build that silently dropped them would still pass check 1.
  for (const required of [
    "/api/anonymous/extract",
    "sw.js",
    "/api/auth",
    "/api/me",
    "/api/articles",
    "/api/notes",
  ]) {
    if (!bundle.includes(required)) {
      console.error(`[reader-release] FAILED: base bundle is missing ${required}`);
      process.exit(1);
    }
  }

  // 3. No source file reaches for a `modules/**` package this tree does not
  //    vendor.
  //
  // The byte check above cannot see this: a file that imports a package this
  // tree does not have would fail the bundle later, in a message about a
  // resolution error rather than about a boundary. Checking the sources is what
  // makes "the boundary holds" a statement about the repository rather than
  // about one build's tree shaking.
  //
  // `modules/` used to be uniformly off limits, on the grounds that everything
  // under it belonged to the paid product. That stopped being true when
  // `phone-otp-kit` was vendored here: it is tracked in this repository, and
  // `server/src/auth.ts` uses it for passwordless phone sign-in, which this
  // product has — `.env.example` documents the `SMS_*` / `PHONE_OTP_*` contract
  // it needs. A check that still failed on it would fail on a capability we
  // ship rather than on a leak, so it now allows the packages listed in
  // `VENDORED_MODULES` and keeps failing on everything else.
  //
  // The commercial packages do not rely on this list: check 1 above fails the
  // built bundle if payment or entitlement markers appear anywhere in it. This
  // list is the earlier tripwire — a *source* import of `modules/payment-kit`
  // is caught here, before it is ever bundled.
  //
  // The pattern matches *import specifiers* — `from "…"`, `import("…")`,
  // `require("…")` — and not any quoted string that happens to contain
  // `modules/`. Prose that names the package in a comment is documentation of
  // the boundary, not a dependency on the other side of it, and a check that
  // failed on a comment would push people to stop writing the comment.
  const VENDORED_MODULES = new Set(["phone-otp-kit"]);
  const SOURCE_ROOTS = ["src", "server/src", "shared"];
  const MODULE_IMPORT =
    /(?:\bfrom\s*|import\s*\(\s*|require\s*\(\s*)["'`][^"'`]*\bmodules\/([^"'`/]+)\//;
  const offenders = [];
  for (const root of SOURCE_ROOTS) {
    for (const file of await walk(path.join(REPO_ROOT, root))) {
      if (!/\.(ts|tsx|mts|cts)$/.test(file)) continue;
      const source = await readFile(path.join(REPO_ROOT, root, file), "utf8");
      const reached = MODULE_IMPORT.exec(source);
      if (reached && !VENDORED_MODULES.has(reached[1])) offenders.push(`${root}/${file}`);
    }
  }
  if (offenders.length > 0) {
    console.error(
      `[reader-release] FAILED: source imports a module outside the vendored set: ${offenders.join(", ")}`,
    );
    process.exit(1);
  }
  if (indexHtml.includes("fonts.googleapis.com") || indexHtml.includes("fonts.gstatic.com")) {
    console.error("[reader-release] FAILED: built index.html still links remote fonts");
    process.exit(1);
  }
  if (!indexHtml.includes("connect-src 'self' https:")) {
    console.error("[reader-release] FAILED: built index.html did not get the base-line CSP");
    process.exit(1);
  }
  const assetStats = await stat(path.join(DIST, "index.html"));
  if (!assetStats.isFile()) {
    console.error("[reader-release] FAILED: dist/index.html missing");
    process.exit(1);
  }

  await emitShell();
  console.log(`[reader-release] built ${DIST} (base ${BASE})`);
}

await main();
